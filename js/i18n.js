// Мова інтерфейсу. Ключ — російський текст, UK — переклад; без збереженого вибору — українська.
// Параметри підставляються як {name}. Вибір мови зберігається на пристрої.
const KEY = 'weight-log:lang';
export const LANGS = { ru: 'Русский', uk: 'Українська' };

let current = load();
const warned = new Set();

function load() {
  try {
    const v = localStorage.getItem(KEY);
    return LANGS[v] ? v : 'uk';
  } catch {
    return 'uk';
  }
}

export const lang = () => current;
export const locale = () => (current === 'uk' ? 'uk-UA' : 'ru-RU');

export function setLang(code) {
  if (!LANGS[code]) return;
  current = code;
  try { localStorage.setItem(KEY, code); } catch { /* приватний режим */ }
}

export function t(key, params) {
  let text = key;
  if (current === 'uk') {
    if (key in UK) text = UK[key];
    else if (!warned.has(key)) { warned.add(key); console.warn('i18n: немає перекладу', key); }
  }
  return params ? text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? params[name] : m)) : text;
}

/** Форма слова за числом: forms — [один, кілька, багато] (1 день, 2 дні, 5 днів). */
export function plural(n, forms) {
  const kind = new Intl.PluralRules(current === 'uk' ? 'uk' : 'ru').select(Math.abs(n));
  return forms[kind === 'one' ? 0 : kind === 'few' ? 1 : 2];
}

/** Статичні тексти index.html: data-i18n — текст, data-i18n-aria — aria-label. */
export function applyStatic() {
  document.documentElement.lang = current;
  document.title = t('Вес');
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}

