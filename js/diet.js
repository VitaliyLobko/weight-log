// Коротка пам'ятка «харчування при діабеті»: що можна і чого уникати; групи — заголовок і перелік.
import { h } from './ui.js';

const ALLOWED = [
  ['Овочі', 'особливо зелені й з низьким ГІ: огірки, капуста, броколі, шпинат, перець, кабачки'],
  ['Білок', 'нежирне м\'ясо, риба, яйця, бобові, тофу'],
  ['Корисні жири', 'горіхи (помірно), авокадо, оливкова олія'],
  ['Цільнозернові', 'гречка, бурий рис, кіноа, вівсянка без цукру'],
  ['Молочні', 'нежирний кефір, йогурт без добавок, сир кисломолочний'],
  ['Фрукти — обмежено', 'з низьким глікемічним індексом: яблука, ягоди, сливи — невеликими порціями'],
];

const AVOID = [
  ['Цукор і солодощі', 'цукор у чистому вигляді й у чаї чи каві; цукерки, шоколад, випічка, печиво; солодкі напої — соки, газовані, енергетики; варення, мед, згущене молоко'],
  ['Біле борошно', 'білий хліб, булки, круасани, білий рис, паста з білого борошна'],
  ['Швидкі вуглеводи й крохмаль', 'картопля (особливо смажена чи пюре), манка, кукурудза, кукурудзяні пластівці'],
  ['Жирне й смажене', 'фастфуд, ковбаси, сосиски, бекон, жирне м\'ясо з прожилками, маргарин'],
  ['Алкоголь', 'особливо пиво, лікери, солодке вино; на голодний шлунок — стрибки цукру'],
];

const TEXT = {
  allowed: 'Можна',
  avoid: 'Не можна',
  note: 'Коротко, для себе. Меню й дози ліків — з лікарем.',
};

function group(cls, title, list) {
  return h('div', { class: `diet-group ${cls}` },
    h('h4', {}, title),
    h('ul', {}, list.map(([name, items]) => h('li', {},
      h('span', { class: 'diet-dot', 'aria-hidden': 'true' }),
      h('span', {}, h('b', {}, name), ' — ', items)))));
}

/** Пам'ятка двома списками: «можна» і «не можна». */
export function dietMemo() {
  return h('div', { class: 'diet' },
    group('good', TEXT.allowed, ALLOWED),
    group('bad', TEXT.avoid, AVOID),
    h('p', { class: 'muted small' }, TEXT.note));
}
